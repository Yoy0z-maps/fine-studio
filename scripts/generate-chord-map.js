#!/usr/bin/env node

/**
 * Regenerates assets/data/chords/CHORD_FILES_MAP.ts from the chord JSON files.
 * Run after adding or editing files under assets/data/chords/<ROOT>/:
 *
 *   node scripts/generate-chord-map.js
 *
 * Each map entry is a loader (`() => require(...)`), so a chord's JSON is evaluated only when a
 * screen actually needs it - not all ~9,000 files (36 MB) the moment the map is imported. Chords
 * whose file has no voicings are listed separately so search can skip them without loading.
 */

const fs = require("fs");
const path = require("path");

const CHORDS_DIR = path.join(__dirname, "..", "assets", "data", "chords");
const OUTPUT = path.join(CHORDS_DIR, "CHORD_FILES_MAP.ts");

const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

const roots = fs
  .readdirSync(CHORDS_DIR, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort(byCodeUnit);

const lines = [];
const withoutVoicings = [];

for (const root of roots) {
  lines.push(`  ${JSON.stringify(root)}: {`);
  const files = fs
    .readdirSync(path.join(CHORDS_DIR, root))
    .filter((file) => file.endsWith(".json"))
    .sort(byCodeUnit);
  for (const file of files) {
    const suffix = file.slice(0, -".json".length);
    const data = JSON.parse(fs.readFileSync(path.join(CHORDS_DIR, root, file), "utf8"));
    if (!Array.isArray(data.positions) || data.positions.length === 0) {
      withoutVoicings.push(`${root}/${suffix}`);
    }
    lines.push(`    ${JSON.stringify(suffix)}: () => require(${JSON.stringify(`./${root}/${file}`)}),`);
  }
  lines.push("  },");
}

const source = `// Generated by scripts/generate-chord-map.js - do not edit by hand.
import type { ChordFileData } from "@/types/chord";

// Loaders, so each chord's JSON is evaluated only when it's first needed (see loadChord).
export const CHORD_FILES_MAP: Record<string, Record<string, () => ChordFileData>> = {
${lines.join("\n")}
};

// "<root>/<suffix>" of files with no voicings yet - skipped by search without loading them.
export const CHORDS_WITHOUT_VOICINGS: ReadonlySet<string> = new Set([
${withoutVoicings.map((key) => `  ${JSON.stringify(key)},`).join("\n")}
]);
`;

fs.writeFileSync(OUTPUT, source);
console.log(
  `Wrote ${path.relative(process.cwd(), OUTPUT)}: ${lines.length - roots.length * 2} chords, ` +
    `${withoutVoicings.length} without voicings`
);
